// Builds js/words.js from a plain word list (one word per line).
//   node tools/build-words.mjs                 # downloads the default list
//   node tools/build-words.mjs path/to/list.txt
// Default source: dolph/dictionary "popular.txt" — ~25k common English words (ENABLE filtered by
// Wiktionary frequency), so accidental matches are words players actually recognise.
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE_URL = 'https://raw.githubusercontent.com/dolph/dictionary/master/popular.txt';

// Slurs/profanity, plus obscure 3-letter Scrabble filler that would clear by surprise.
const BLOCKLIST = new Set(`
  fag fags faggot faggots jew jews lez dyke dykes homo homos nigger niggers nigga spic spics chink chinks
  gook gooks wop wops coon coons kike kikes retard retards tranny slut sluts whore whores cunt cunts twat
  twats cum jizz dildo dildos tits titty boob boobs cock cocks dick dicks pussy porn penis vagina rape
  raped rapes rapist shit shits shitty fuck fucks fucked fucker fucking crap bitch bitches bastard piss
  pissed nazi nazis ass arse wank wanker sex sexy
  aga ain ala als ama ana ane ani att ava bel ben bey cee col cor cos coz dah dee del dex dey dis dit dol
  dom dos dui eng ers ess eta eth fer gat ged gib gor hap hep hic hon hoy hup ich iff jus kat kay lar las
  lin lis lum mae mas mel mil mis mol mon mor nam noh noo nos ole ops ort ose pac pam pap pas pis pom ree
  rin rom rya sal sen ser sha sim sri tae tas tet til tis tod tor uns vee vig vis wha yeh yom
`.split(/\s+/).filter(Boolean));

const text = process.argv[2]
  ? await readFile(process.argv[2], 'utf8')
  : await (await fetch(SOURCE_URL)).text();

const words = [...new Set(text.split(/\s+/).map(w => w.trim().toLowerCase()))]
  .filter(w => /^[a-z]{3,}$/.test(w) && !BLOCKLIST.has(w))
  .filter(w => !/q(?!u)/.test(w)) // Q only exists as a QU tile, so a bare Q can never be spelled
  .sort();

const out = `// Generated by tools/build-words.mjs (${words.length} words). Do not edit by hand.\n`
  + `window.WORDLIST = ${JSON.stringify(words.join(' '))};\n`;
await writeFile(new URL('../js/words.js', import.meta.url), out);
console.log(`wrote js/words.js: ${words.length} words`);
