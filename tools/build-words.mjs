// Builds js/words.js from a plain word list (one word per line).
//   node tools/build-words.mjs                         # downloads the default lists
//   node tools/build-words.mjs path/to/list.txt [path/to/frequency.txt]
// Default source: dolph/dictionary "popular.txt" — ~25k common English words (ENABLE filtered by
// Wiktionary frequency), so accidental matches are words players actually recognise.
// Target words come from the most frequent words of first20hours/google-10000-english, so the dealer
// only ever asks for words everyone knows.
import { readFile, writeFile } from 'node:fs/promises';

const SOURCE_URL = 'https://raw.githubusercontent.com/dolph/dictionary/master/popular.txt';
const FREQ_URL = 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt';
const TARGET_RANK = 6000; // only the most common words make good targets

// Slurs/profanity, plus obscure 3-letter Scrabble filler that would clear by surprise.
const BLOCKLIST = new Set(`
  fag fags faggot faggots jew jews lez dyke dykes homo homos nigger niggers nigga spic spics chink chinks
  gook gooks wop wops coon coons kike kikes retard retards tranny slut sluts whore whores cunt cunts twat
  twats cum jizz dildo dildos tits titty boob boobs cock cocks dick dicks pussy porn penis vagina rape
  raped rapes rapist shit shits shitty fuck fucks fucked fucker fucking crap bitch bitches bastard piss
  pissed nazi nazis ass arse wank wanker sex sexy
  aga ain ala als ama ana ane ani att ava bel ben bey cee col cor cos coz dah dee del dex dey dis dit dol
  dom dos dui eng ers ess eta eth fer gat ged gib gor hap hep hic hon hoy hup ich iff jus kat kay lar las
  lin lis lum mae mas mel mil mis mol mon mor nam noh noo nos ole ops ort ose pac pam pap pas pis pom ree
  rin rom rya sal sen ser sha sim sri tae tas tet til tis tod tor uns vee vig vis wha yeh yom
`.split(/\s+/).filter(Boolean));

const load = (path, url) => (path ? readFile(path, 'utf8') : fetch(url).then(r => r.text()));
const text = await load(process.argv[2], SOURCE_URL);
const freqText = await load(process.argv[3], FREQ_URL);

const words = [...new Set(text.split(/\s+/).map(w => w.trim().toLowerCase()))]
  .filter(w => /^[a-z]{3,}$/.test(w) && !BLOCKLIST.has(w))
  .filter(w => !/q(?!u)/.test(w)) // Q only exists as a QU tile, so a bare Q can never be spelled
  .sort();

// Targets: 5-7 letters, no rare letters (they would also need QU tiles), no plurals ending in S.
const known = new Set(words);
const targets = [...new Set(freqText.split(/\s+/).slice(0, TARGET_RANK))]
  .filter(w => known.has(w) && w.length >= 5 && w.length <= 7 && !/[jkqvxz]/.test(w) && !w.endsWith('s'));

// SHORT FUSE: common 2-letter words, kept only if the source list has them and they are not blocked.
const SHORT_CANDIDATES = `ah am an as at aw be by do eh go ha he hi ho if in is it la lo ma me my no of oh ok on or ow ox
  pa so to uh um up us we ya ye yo`.split(/\s+/).filter(Boolean);
const sourceAll = new Set(text.split(/\s+/).map(w => w.trim().toLowerCase()));
const shorts = SHORT_CANDIDATES.filter(w => sourceAll.has(w) && !BLOCKLIST.has(w));

const out = `// Generated by tools/build-words.mjs (${words.length} words, ${targets.length} targets). Do not edit by hand.\n`
  + `window.WORDLIST = ${JSON.stringify(words.join(' '))};\n`
  + `window.TARGETS = ${JSON.stringify(targets.join(' '))};\n`
  + `window.SHORTWORDS = ${JSON.stringify(shorts.join(' '))};\n`;
await writeFile(new URL('../js/words.js', import.meta.url), out);
console.log(`wrote js/words.js: ${words.length} words, ${targets.length} targets, ${shorts.length} short words`);
